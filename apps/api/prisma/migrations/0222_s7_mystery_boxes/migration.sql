-- Order independent: it touches only mystery_* tables, so it applies after any later migration on a fresh database.

-- CreateTable
CREATE TABLE "mystery_boxes" (
    "id" INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "label" TEXT NOT NULL,
    "cost_syiling" INTEGER NOT NULL,
    "is_active" BOOLEAN NOT NULL DEFAULT true,
    "created_at" TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "updated_at" TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT "mystery_boxes_pkey" PRIMARY KEY ("id")
