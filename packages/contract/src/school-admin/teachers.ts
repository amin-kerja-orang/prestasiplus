import { z } from '../zod'
import { IdSchema } from '../common/ids'
import { TimestampSchema } from '../common/time'
import { count, nonBlank, SchoolAdminInitialCredentialSchema } from './common'
import { SchoolAdminUserDetailSchema, SchoolAdminUserListMetaSchema } from './users'

/**
 * Teacher management of the Admin Sekolah (S7, S10, S11): list, detail, CSV export, create, update,
 * toggle active, reset password. Routes are under `/admin-sekolah/guru`.
 */

export const SchoolAdminTeacherRowSchema = z
  .object({
    id: IdSchema,
    name: z.string(),
    initials: z.string().min(1).max(2).meta({ description: 'Up to two upper-case initials.' }),
    email: z.string(),
    phone: z.string().nullable(),
    classCount: count.meta({ description: 'Active classes owned by the teacher.' }),
    lastLoginAt: TimestampSchema.nullable(),
    isActive: z.boolean(),
    createdAt: TimestampSchema,
    canEdit: z.boolean().meta({ description: 'True only for an active teacher (equals isActive).' }),
  })
  .meta({ id: 'SchoolAdminTeacherRow' })
export type SchoolAdminTeacherRow = z.infer<typeof SchoolAdminTeacherRowSchema>

/** Active first, then id descending; 25 per page. */
export const SchoolAdminTeacherListResponseSchema = z
  .object({ data: z.array(SchoolAdminTeacherRowSchema), meta: SchoolAdminUserListMetaSchema })
  .meta({ id: 'SchoolAdminTeacherListResponse' })
export type SchoolAdminTeacherListResponse = z.infer<typeof SchoolAdminTeacherListResponseSchema>

/**
 * `POST /admin-sekolah/guru` body. The teacher is created ACTIVE, with role teacher and the caller
 * school; `role`, `schoolId` and any other key are ignored (mass-assignment waiver of BE-NFR-05, see
 * the create-pupil route). Validation (422, Laravel English text):
 * `name` required, at most 255; `email` required, valid, at most 255, unique among ALL users
 * (cross-school, accepted enumeration trade-off); `phone` at most 14. There is NO `password` or
 * `passwordConfirmation` field (D59b): the server always generates a random initial password
 * (CSPRNG, at least 12 characters), returns it once in `credential.password` and flags the account
 * `mustChangePassword`; a password key sent by an old client is ignored, never bound. The mock UI
 * required an admin-typed password pair here; that is dropped (see the deviations log).
 */
export const SchoolAdminTeacherCreateRequestSchema = z
  .object({
    name: nonBlank(255),
    email: z.email().max(255),
    phone: z.string().max(14).nullable().optional(),
  })
  .meta({ id: 'SchoolAdminTeacherCreateRequest' })
export type SchoolAdminTeacherCreateRequest = z.infer<typeof SchoolAdminTeacherCreateRequestSchema>

/**
 * `201` result of `POST /admin-sekolah/guru` (D55c, D59b): `{ data, credential, mustChangePassword,
 * status }` like the pupil create. `credential.password` is generated by the server, shown once to
 * the creating school admin, never logged, never re-served (recovery: reset-password);
 * `mustChangePassword` is always true (enforced by BE-03).
 */
export const SchoolAdminTeacherCreatedResultSchema = z
  .object({
    data: SchoolAdminUserDetailSchema,
    credential: SchoolAdminInitialCredentialSchema,
    mustChangePassword: z.literal(true).meta({
      description:
        'Always true on create (D59b): the new teacher account is flagged must-change-password, so the first login forces a password change (enforced by BE-03).',
    }),
    status: z.string().min(1).meta({ description: 'Pengguna berjaya didaftarkan.' }),
  })
  .meta({ id: 'SchoolAdminTeacherCreatedResult' })
export type SchoolAdminTeacherCreatedResult = z.infer<typeof SchoolAdminTeacherCreatedResultSchema>

/** `data: { isActive }` is the NEW state; status "Status pengguna berjaya dikemaskini.". */
export const SchoolAdminToggleActiveResultSchema = z
  .object({ data: z.object({ isActive: z.boolean() }), status: z.string().min(1) })
  .meta({ id: 'SchoolAdminToggleActiveResult' })
export type SchoolAdminToggleActiveResult = z.infer<typeof SchoolAdminToggleActiveResultSchema>
