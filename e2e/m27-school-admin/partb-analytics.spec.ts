test.describe('S1 responsive (E2E-M27-43)', MODULE, () => {
  for (const [who, name] of [
    [AZLAN, 'P1'],
    [POPULATED, 'P4'],
  ] as const) {
    test(`E2E-M27-43 ${name}: no horizontal scroll, text at least 12 px, tiles 2 per row at 375 and 4 + 3 from 768, table inside its card`, async ({
      page,
      gotoApp,
    }) => {
      await signIn(page, who)
      await open(page, gotoApp)
      await expectNoHorizontalScroll(page)
      const width = viewportWidth(page)

      const small = await page.getByTestId('su-page').evaluate((root) => {
        const bad: string[] = []
        const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT)
        for (let n = walker.nextNode(); n; n = walker.nextNode()) {
          if (!(n.textContent ?? '').trim()) continue
          const el = n.parentElement!
          if (parseFloat(getComputedStyle(el).fontSize) < 12) bad.push(`${el.tagName}:${n.textContent}`)
        }
        return bad
      })
      expect(small).toEqual([])

      const tops = await page
        .locator('[data-testid="su-tiles"] > *')
        .evaluateAll((els) => els.map((e) => Math.round(e.getBoundingClientRect().top)))
      const perRow = new Map<number, number>()
      for (const t of tops) perRow.set(t, (perRow.get(t) ?? 0) + 1)
      const rowSizes = [...perRow.values()]
      if (width >= 768) expect(rowSizes).toEqual([4, 3])
      else expect(rowSizes).toEqual([2, 2, 2, 1])

      // every pill is a 44 px touch target
      for (const p of PERIODS) {
        const box = (await page.getByTestId(`su-pill-${p}`).boundingBox())!
        expect(box.height).toBeGreaterThanOrEqual(43.5)
      }

      // the mode table (or the empty card) stays inside the page width
      const card = page.getByTestId('su-modes').or(page.getByTestId('su-empty'))
      const box = (await card.boundingBox())!
      expect(box.x).toBeGreaterThanOrEqual(0)
      expect(box.x + box.width).toBeLessThanOrEqual(width + 0.5)
      if (await page.getByTestId('su-modes-scroll').count()) {
        expect(
          await page
            .getByTestId('su-modes-scroll')
            .evaluate((e) => getComputedStyle(e).overflowX === 'auto'),
        ).toBe(true)
      }
    })
  }
})

