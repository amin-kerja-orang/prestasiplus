async function openS3(
  page: Page,
  gotoApp: (p: string) => Promise<void>,
  query = '',
): Promise<void> {
  await gotoApp(`${S3}${query}`)
  // the populated schools are computed from large owner datasets: allow the first answer time
  await expect(page.getByTestId('la-tabs')).toBeVisible({ timeout: 60_000 })
}

/** Waits for the answer of a range after an in-app navigation (the previous figures stay while it loads). */
async function gotoRange(page: Page, range: number): Promise<void> {
  await spaGoto(page, `${S3}?range=${String(range)}`)
  await expect(page.getByTestId('la-page')).toHaveAttribute('data-range', String(range), {
    timeout: 60_000,
  })
}

